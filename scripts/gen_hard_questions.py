def stable_int(s: str) -> int:
    return int(hashlib.md5(s.encode("utf-8")).hexdigest(), 16)


def make_distractors(correct, qid):
    """正解ベクトルから、重複しない撹乱4肢を決定的に生成する。"""
    n = len(correct)
    seed = stable_int(qid)
    seen = {tuple(correct)}
    out = []
    # 1ビット反転（n通り）を seed 起点の順で
    order = [(seed >> i) % n for i in range(16)]
    candidates = []
    # まず全1ビット反転
    for i in range(n):
        v = correct[:]
        v[i] = not v[i]
        candidates.append(v)
    # 次に全2ビット反転
    for i in range(n):
        for j in range(i + 1, n):
            v = correct[:]
            v[i] = not v[i]
            v[j] = not v[j]
            candidates.append(v)
    # seedで順番をシャッフル（決定的）
    candidates.sort(key=lambda v: stable_int(qid + "".join("1" if x else "0" for x in v)))
    for v in candidates:
        t = tuple(v)
        if t not in seen:
            seen.add(t)
            out.append(v)
        if len(out) == 4:
            break
    return out


