def build():
    out = []
    correct_by_id = {q[0]: [s[1] for s in q[3]] for q in QUESTIONS}
    for qid, cat, topic, stmts in QUESTIONS:
        assert len(stmts) == 4, qid
        correct = [s[1] for s in stmts]
        distractors = make_distractors(correct, qid)
        pos = stable_int(qid + "_pos") % 5
        options = distractors[:]
        options.insert(pos, correct)
        expl = "　".join(
            f"{LABELS[i]}（{'正' if stmts[i][1] else '誤'}）"
            f"{'正しい記述です。' if stmts[i][1] else '誤った記述です。'}{stmts[i][2]}"
            for i in range(4)
        )
        out.append({
            "id": qid,
            "type": "seigo_combination",
            "category": cat,
            "year": 2026,
            "prefecture": "手引き令和8年4月改訂",
            "text": f"{topic}に関する次の記述について、正しい正誤の組み合わせを一つ選びなさい。",
            "statements": [{"label": LABELS[i], "text": stmts[i][0]} for i in range(4)],
            "seigo_options": options,
            "correctIndex": pos,
            "explanation": expl,
            "difficulty": 3,
        })

    # 自己検証
    ids = [q["id"] for q in out]
    assert len(ids) == len(set(ids)), "ID重複"
    for q in out:
        assert len(q["seigo_options"]) == 5, q["id"]
        assert len({tuple(o) for o in q["seigo_options"]}) == 5, f"撹乱肢重複 {q['id']}"
        assert q["seigo_options"][q["correctIndex"]] == correct_by_id[q["id"]], q["id"]

    path = ROOT / "src" / "data" / "questions" / "r8_tebiki_questions.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    from collections import Counter
    ch = Counter(q["category"] for q in out)
    print(f"生成 {len(out)} 問 -> {path.name}")
    print("  章別:", {k[:6]: v for k, v in ch.items()})


if __name__ == "__main__":
    build()
